# Datatypes : a kind of value a variable hold
# str    → Text
# int    → Whole numbers
# float  → Decimal numbers
# bool   → True / False

#Strings : Strings are  sequence of characters enclosed in single or double quotes.
str1 = "Welcome to Python"
str2 = "Python is fun to Learn"
print("Greeting:",str1)
print("Hey!",str2)
print(type(str1))
print(type(str2))

#Integers: Integers are whole numbers without decimals points.
my_integer_var = 10
print("Integer:",my_integer_var)
print(type(my_integer_var))

#Float: Float ae numbers with decimal points.
my_float_var = 10.5
print("Float:",my_float_var)
print(type(my_float_var))

#Boolean: Boolean is a datatype that can hold one of two values: True or False.
my_bool_var = True
print("Boolean:",my_bool_var)
print(type(my_bool_var))
   






