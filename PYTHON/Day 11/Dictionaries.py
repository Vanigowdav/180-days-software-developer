# Dictionaries : are built in data structure that store collections of key-value pairs.
# syntax : { key1: value1, key2 : value2.......}
# key must be unique in the dictionary and must be immutable datatype , values can be repeated.

pizza = {
    'name' : 'Margheritta Pizza',
    'price' : 8.9,
    'colories_per_slice' : 250,
    'toppings' : ['mozzarella', 'basil']
}
print(pizza)

