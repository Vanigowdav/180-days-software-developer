# #Conditional statements: ae used to perform different actions based on different conditions.
# #In python we have the following conditional statements:



# 1.if statement: It is used to test a specific condition. If the condition is true, the block of code inside the if statement is executed.
# 2. else statement: It is used to execute a block of code when the condition in the if statement is false.
# 3. elif statement: It is used to test multiple conditions. If the condition in the if statement is false, the condition in the elif statement is tested.
# 4. nested if statement: It is used to test multiple conditions by placing an if statement inside another if statement.
# 5. ternary operator(condition ? value1 : value2): It is used to test a condition and return a value based on the condition. It is also called conditional expression.
# 6. switch statement: It is used to test a specific condition and execute a block of code based on the value of the condition. It is also called match statement in python.
# 7. pass statement: It is used as a placeholder for future code. It is also used to create an empty block of code.   
# 8. break statement: It is used to exit a loop or switch statement. It is also used to terminate the current iteration of a loop and move to the next iteration.
# 9. continue statement: It is used to skip the current iteration of a loop and move to the next iteration.

