# Inheritance : It helps to reuse the code 
# With inheritance a subclass(or child class) can use the attributes and methods of a base class(or parent class)
# This helps to reuse code, create clear class, hierarchies and customize behaviour without rewriting everything.

# Syntax:
# class Parent:
    # Parent attributes and method

# class Child(Parent):
    # child inherits, extends, and/or overrides when necessary

# Types of inheritance:
# 1. Single Inheritance: a child class inherits from exactly one parent class.
# 2. Multiple Inheritance: child calss can inherit from more then one parent class.


