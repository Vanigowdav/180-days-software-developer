# Oops - Object Oriented Programming : is a programming style in which developers treat everything in their code like a real-world object.
# Object-oriented programming has four key principles 
# - Encapsulation 
# - Inheritance
# - Polymorphism 
# - Abstraction 

# 1. Encapsulation: involves wrapping attributes and methods that operate on that data within single unit. such as class
#                   This protects data from external innterference and misuse, improving security and maintainability.

# 2. Abstraction: hides the complex inner workings of an object, exposing only the essential parts for interaction. 

# 3. Inheritance: Inheritance allows a class to inherit attributes and methods from another class, facilitating reuse. 

# 4. Polymorphism: allows objects of different classes to be treated as objects of a common superclass , but they can behave differently depending on the object type. 

  