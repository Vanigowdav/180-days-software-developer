# Exception Handling : is an unexpected event that disrupts the normal flow of a program.
# It allows us to manage these situations gracefully, preventing crashes.

# What is exception?
# An exception is an event that occurs during the exception of a program that disrupts the normal flow of instructions.

# Built-in Exceptions 
# 1. ZeroDivisionError : Raised when dividing by zero.
# 2. ValueError : Raised when a function receives an argument of the right type but an inappropriate value.
# 3.  TypeError : Raised when an operation is applied to an object of inappropriate type.
# 4. IndexError : Raised when accessing an index that is out of range in a list or tuple.

