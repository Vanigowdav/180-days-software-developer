# Strings Interpolation : inserting variables and expressions into a string 
# F-strings in python used to handle interpolation 
# F - strings start with f (lower or uppercase) before the quotes.
# Uses {} curly braces to embed variables or expressions.

greeting = 'Hi'
greeting1 = "Welcome"
print(f'{greeting}! Maya {greeting1} to my home')

num1 = 5
num2 = 6
num1_and_num2 = f'Sum of {num1} and {num2} is {num1 + num2}'
print(num1_and_num2)


